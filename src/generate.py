FONT_MONO = "ui-monospace,'SF Mono','Menlo','Cascadia Code','Consolas','Liberation Mono',monospace"

def format_points(n: int) -> str:
    if n >= 1_000_000: return f"{n / 1_000_000:.1f}".rstrip('0').rstrip('.') + 'M'
    if n >= 10_000: return f"{n / 1_000:.1f}".rstrip('0').rstrip('.') + 'K'
    if n >= 1_000: return f"{n:,}"
    return str(n)

def level_to_hex(n: int) -> str: return f"0x{n:X}"

def level_to_title(n: int) -> str:
    titles = [
        'NEOPHYTE', 'APPRENTICE', 'PATHFINDER', 'SEEKER', 'VISIONARY',
        'VOYAGER', 'ADEPT', 'HACKER', 'MAGE', 'WIZARD',
        'MASTER', 'GURU', 'LEGEND', 'GUARDIAN', 'TITAN',
        'SAGE', 'VANGUARD', 'SHOGUN', 'ASCENDED', 'MYTHIC', 'GRANDMASTER',
    ]
    idx = min(n - 1, len(titles) - 1)
    return titles[idx] if idx >= 0 else 'NEOPHYTE'

CAPABILITY_PALETTES = {
    'red':   {'from': '#ff8a6b', 'to': '#e94e3a'},
    'green': {'from': '#c5cfff', 'to': '#5a7cff'},
}

def capability_palette(pov: str) -> dict:
    return CAPABILITY_PALETTES.get(pov, CAPABILITY_PALETTES['red'])

def escape_xml(s: str) -> str:
    return str(s).replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;').replace('"', '&quot;').replace("'", '&apos;')

def set_github_output(name: str, value: str):
    gh_out = os.environ.get("GITHUB_OUTPUT")
    if gh_out:
        with open(gh_out, "a", encoding="utf-8") as f:
            f.write(f"{name}={value}\n")

