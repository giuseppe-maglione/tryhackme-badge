def main():
    username = os.environ.get("THM_USERNAME", "").strip()
    if not username:
        if len(sys.argv) > 1:
            username = sys.argv[1]
        else:
            sys.stderr.write("[thm-badge] FATAL: THM_USERNAME env var is required.\n")
            sys.exit(1)

    output_path = os.environ.get("OUTPUT_PATH", "assets/thm_badge.svg")
    theme_input = os.environ.get("THEME", "rotate")
    accent_override = os.environ.get("ACCENT_COLOR", "").strip()

    theme_name = pick_theme(theme_input)
    theme = dict(THEMES[theme_name])
    if accent_override:
        theme['accent'] = accent_override
        theme['border'] = accent_override
    
    print(f"[thm-badge] Theme: {theme_name}" + (f" (accent override: {accent_override})" if accent_override else ""))
    print(f"[thm-badge] Fetching profile for \"{username}\"...")

    try:
        json_resp = fetch_profile_data(username)
    except Exception as e:
        sys.stderr.write(f"[thm-badge] FAILED: {e}\n")
        sys.exit(1)

    if json_resp.get("status") != "success" or not json_resp.get("data"):
        sys.stderr.write(f"[thm-badge] Unexpected API payload: {str(json_resp)[:200]}\n")
        sys.exit(1)

    data = json_resp["data"]
    svg_content = build_svg(data, theme, theme_name)
    
    out_file = Path(output_path)
    out_file.parent.mkdir(parents=True, exist_ok=True)
    out_file.write_text(svg_content, encoding="utf-8")
    
    set_github_output("theme_used", theme_name)
    set_github_output("rank", str(data.get("rank", 0)))
    
    print(f"[thm-badge] Wrote {output_path}")
    print(f"[thm-badge] Stats: rank #{data.get('rank', 0)} · top {data.get('topPercentage', '?')}% · {data.get('completedRoomsNumber', 0)} rooms · {data.get('badgesNumber', 0)} badges · level {data.get('level', 1)} ({level_to_hex(data.get('level', 1))})")

if __name__ == "__main__":
    main()